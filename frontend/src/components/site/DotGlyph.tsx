/*
 * 7x7 dot-matrix icons. In a pattern row:
 *   "#" is a full dot, "+" a medium dot, "." a faint grid dot.
 */

export const glyphs = {
  document: ["#####..", "#+++##.", "#+++++#", "#.###.#", "#.....#", "#.####.", "#######"],
  chunks: ["###.###", "###.###", ".......", "###.###", "###.###", ".......", "###.+++"],
  embedding: ["#.....+", "..+..#.", ".#..+..", "...#...", "..+..#.", ".#..+..", "+.....#"],
  search: ["..###..", ".#...#.", "#..+..#", "#.+#+.#", "#..+..#", ".#...##", "..###.#"],
  answer: ["#######", "#.....#", "#.###.#", "#.....#", "#######", "..##...", "..#...."],
  citation: ["##...##", "#.....#", "#.#.#.#", "#.#.#.#", "#.....#", "#..+..#", "##...##"],
  api: ["..#.#..", ".#...#.", ".#...#.", "#..+..#", ".#...#.", ".#...#.", "..#.#.."],
  validate: ["......#", ".....##", "#...##.", "##.##..", ".###...", "..#....", "......."],
  database: [".#####.", "#.....#", ".#####.", "#.....#", ".#####.", "#.....#", ".#####."],
  evaluation: ["......#", "......#", "....#.#", "....#.#", "..#.#.#", "#.#.#.#", "#######"],
  observe: [".......", "..#....", "..##...", "#.#.#.#", "##..#.#", "....##.", "......."],
  shield: ["#######", "#+++++#", "#+.#.+#", "#+###+#", ".#+#+#.", "..#+#..", "...#..."],
  rank: ["#######", ".......", "#####..", ".......", "###....", ".......", "#......"],
  filter: ["#######", ".#####.", "..###..", "...#...", "...#...", "...#...", "...+..."],
  refuse: ["..###..", ".#...##", "#...#.#", "#..#..#", "#.#...#", "##...#.", "..###.."],
  lock: ["..###..", ".#...#.", ".#...#.", "#######", "###.###", "###.###", "#######"],
} as const;

export type GlyphName = keyof typeof glyphs;

export function DotGlyph({
  name,
  size = 44,
  className = "",
}: {
  name: GlyphName;
  size?: number;
  className?: string;
}) {
  const rows = glyphs[name];
  const step = 10;
  return (
    <svg
      viewBox={`0 0 ${step * 7} ${step * 7}`}
      width={size}
      height={size}
      aria-hidden="true"
      className={className}
    >
      {rows.flatMap((row, y) =>
        [...row].map((cell, x) => (
          <circle
            key={`${x}-${y}`}
            cx={x * step + step / 2}
            cy={y * step + step / 2}
            r={cell === "#" ? 3.6 : cell === "+" ? 2.4 : 1.1}
            fill="currentColor"
            opacity={cell === "#" ? 1 : cell === "+" ? 0.55 : 0.22}
          />
        )),
      )}
    </svg>
  );
}
